                                    <p class="faq-text"><strong>GANGOTRI:</strong> Built around the 18th century, Gangotri temple is a temple dedicated to Goddess Ganga. Gorkha General Amar Singh Thapa built the temple. The temple lies near a sacred stone where King Bhagirath worshipped Lord Shiva. The sacred stone is Shivling, which is submerged in the river. This natural rock Shivling is the spot where, according to mythology, Lord Shiva sat when he received Ganga in his tangled lock. The stone is most visible during winter months when the water level decreases. There is another legend that Pandavas performed the great Deva Yagna here to atone their sins of killing their kin in the massive battle of Mahabharata. The temple is an exotic structure with a height of 20ft, made of white granite.</p>
                                    <p class="faq-text"><strong>KEDAR GANGA SANGAM:</strong> About a hundred Yards from the Ganga Temple, the river Kedar Ganga flows. Starting from the Kedar Valle, this river meets the Bhagirathi on its left bank.</p>
                                    <p class="faq-text"><strong>GANGNANI:</strong> If you walk further up from Gangotri, you will see a hot water spring at Gangnani. There is a Kund called Rishikund where you can have a rejuvenating bath at natural hot water spring. There is also a temple of the Sage Parashar near the spring. The sage Parashar is believed to be the father of Ved Vyas.</p>
                                    <p class="faq-text"><strong>RITUAL AND ACTIVITIES:</strong> Perform Snan at Gangotri Ghat (VIP Ghat), Ganga Pujan & Aarti at Gangotri Ghat, Darshan of Bhagirath Shila, Darshan of Gauri Ganesha Temple, Finally Gangotri Temple Darshan after that you will offer prayer to Surya Kund. While returning from Gupteshwar Mahadev temple in Dharali, communicate with Tibetan people and learn more about their culture in Harsil.</p>
