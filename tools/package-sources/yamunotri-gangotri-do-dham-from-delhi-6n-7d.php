                                    Also, you can take a bath in the natural warm water of Jamunabai Kund; you can offer prayer near the temple to Divya Shila. Then, you can move to the temple of Goddess Yamuna and offer your prayers before returning to Barkot. After offering prayers and enjoying the surrounding view, we trek back to Janki Chatti. Then, we will drive back to Barkot, where we will spend the night.</p>
