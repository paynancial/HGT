                                    <p class="faq-text">Morning after breakfast, drive to Uttarkashi. Check into the hotel arrival in Uttarkashi. Visit Kashi Vishwanath Temple in Uttarkashi. Overnight stay at Uttarkashi.</br>
                                    <strong>Uttarkashi</strong> is home to a number of ashrams, temples. The name of the town reflects its similarity to and location (as north of) the city of Kashi (Varanasi). Similar to Varanasi, the town of Uttarkashi is also situated on the banks of River Ganga.</p>

                                    <p class="faq-text"><strong>Vishwanath Temple –</strong>  – Vishwanath temple is one of the oldest Shiva temples in Northern India. Re-constructed in 1857 by Maharani Khaneti Devi of Tehri State in the ancient architectural style. It is situated at the heart of the town. A massive iron trident, symbolic of divine mother’s, is erected and worshiped from time immemorial at the temple complex. Ganeshji, Sakshi Gopal, Markandeya Rishi’s small shrines are also part of the temple complex. Akhand Jyoti as well as Akhand Abhishek, special aarti in morning and evening are offered. As per Skanda Puran, Uttarkashi is known as ‘Saumya Varanasi’, the abode of Lord Shiva in Kaliyug, and counted as one of the twelve Jyotirlingas.</p>

                                    <p class="faq-text"><strong>Shakti Temple –</strong> Right in front of the Vishwanath temple is Shakti temple. It has a big ‘Trishul’ of about 6 meters in height and a circumference of 90 cms. at bottom. Though there are different views about the making of this, the upper part of it seems to be made up of iron and the lower one is of copper. As per the epics, this Shakti was thrown on the devils by the Goddess Durga(Shakti), hence it gets its name. Since then this Shakti is erected over here.</p>

                                    <p class="faq-text"><strong>Uttarkashi Weather –</strong> Generally hot in summer, the temperature ranges from 30-35 degree Celsius but nights is pleasant, Cold in winters.</p>
                                    
