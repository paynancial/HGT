                                    <p class="faq-text"><strong>By Trek - </strong> Though it is difficult to go up and down from Sonprayag on the same day by trek. But it can be done if you take ponies or a helicopter while going to Kedarnath. Do coordinate well with the driver, as due to parking issue driver cannot stay at Sonprayag also network issue is also there.</p>

                                    <p class="faq-text"><strong>Kedarnath - </strong> The Kedarnath shrine, one of the 12 jyotirlingas of Lord Shiva, is a scenic spot situated, against the backdrop of the majestic Kedarnath range. Kedar is another name of Lord Shiva. According to legend, the Pandavas after having won over the Kaurava in the Kurukshetra war felt guilty of having killed their own brothers and sought the blessings of Lord Shiva for redemption. He eluded them repeatedly and while fleeing took refuge at Kedarnath in the form of a bull. On being followed he dived into the ground, leaving his hump on the surface. The remaining portions of Lord Shiva appeared at four other places and are worshipped there as his manifestations. The arms appeared at Tungnath, the face at Rudranath, the belly at Madhmaheshwar, and his locks (hair) with the head at Kalpeshwar. Kedarnath and the four above-mentioned shrines are treated as Panch Kedar.</p>

                                    <p class="faq-text"><strong>Kedarnath Weather - </strong> Due to its high altitude the weather in Kedarnath remains cold for the most part of the year. Summer here is cool and pleasant while winter is severe. During the summer season, the temperature varies around 20°Celsius. Light woolen wear is recommended. The Winter season in Kedarnath is severe with the mercury falling to as low as 0°Celsius. During this time the place experiences snowfall as well. Due to the extreme climatic conditions, this time is usually avoided by tourists.</p>
