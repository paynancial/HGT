                                    <p class="faq-text"><strong>Mana Village :</strong> Inhabited by an Indo-Mongolian tribe, it is the last Indian village before Tibet.</br>
                                    <strong>Vasundhara :</strong> As the name suggests, Vasundhara is a magnificent waterfall. This place is 5km. from Badrinath out of which 2km. is motorable upto Mana.</br>
                                    <strong>Bhim Pul :</strong> On the other side of Mana village, a massive rock forming a natural bridge, lies over the roaring Saraswati river. It presents a spectacular view of water thundering down through the narrow passage under the rock and is believed to have been placed there by Bhim, the second eldest among the five Pandava brothers.</br>
                                    <strong>Vyas Gufa (cave) :</strong> Near Mana Village, this is a rock-cave where Ved Vyas is believed to have composed the Mahabharata and the pauranic commentaries.</br></p>
                                    <p class="faq-text"><strong>Badrinath Weather:</strong> The average maximum temperature will be around 18° Celsius and the average minimum is 8° Celsius. Warm and woolen clothes are hence required for a stay in Badrinath throughout the year. Winter in Badrinath is often accompanied by snowfalls. Winter is very chilly with an average temperature of 5° Celsius. Due to the extreme climatic conditions, this time is usually closed for tourists.</p>
