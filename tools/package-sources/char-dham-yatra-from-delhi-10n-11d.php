                                    <p class="faq-text"><strong>Guptakashi -</strong> The name Gupt Kashi means “Hidden Benares. Mythology describes how when the Pandava brothers were searching for a glimpse of Shiva, Shivji first concealed himself at Guptkashi, but later fled from them further up the valley to Kedarnath, where the Pandavas finally got their wish fulfilled.</p>
